"""Data layer: Dataset, Worksheet, Column, DataTransformation.

Source: S2 3.3, docs/05-data-model.md 5.3, ADR 0001 (cell storage).

IRREVERSIBLE (docs/08-roadmap.md 8.6): ``DataTransformation`` is an ORDERED, REPLAYABLE
log. The spec's own provenance example is "Normalization -> Log transformation" (S2
L770) -- a two-step chain. A flag-based design cannot satisfy Trace Figure.
"""
from __future__ import annotations

from datetime import datetime

from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from scix.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin, enum_col, optional_enum_col
from scix.models.enums import ColumnDataType, TransformType


class Dataset(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One uploaded file.

    ``storage_key`` is WRITE-ONCE. The uploaded original is never mutated -- it is what
    S2 3.13 reports as "Source: Experiment_01.xlsx". Everything downstream derives.
    """

    __tablename__ = "datasets"

    project_id: Mapped[str] = mapped_column(
        ForeignKey("projects.id", ondelete="CASCADE"), index=True, nullable=False
    )
    source_filename: Mapped[str] = mapped_column(String(512), nullable=False)
    storage_key: Mapped[str] = mapped_column(String(1024), nullable=False)
    content_hash: Mapped[str | None] = mapped_column(String(64), index=True)
    file_size_bytes: Mapped[int | None] = mapped_column(Integer)
    mime_type: Mapped[str | None] = mapped_column(String(128))
    row_count: Mapped[int | None] = mapped_column(Integer)
    column_count: Mapped[int | None] = mapped_column(Integer)
    # Which sheets were found at import, before the user chose which to keep.
    sheet_names: Mapped[list | None] = mapped_column()
    imported_by_id: Mapped[str | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))

    __table_args__ = (Index("ix_datasets_project_hash", "project_id", "content_hash"),)

    worksheets: Mapped[list["Worksheet"]] = relationship(
        back_populates="dataset", cascade="all, delete-orphan"
    )


class Worksheet(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """A sheet within a dataset. S2 3.3 "Worksheet 1".

    ``column_store_key`` points at a Parquet file of the cell values (ADR 0001). It is
    REGENERATED by every transformation, so a worksheet's current state is always
    reconstructible by replaying its chain.
    """

    __tablename__ = "worksheets"

    dataset_id: Mapped[str] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    ordinal: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    row_count: Mapped[int | None] = mapped_column(Integer)
    column_store_key: Mapped[str | None] = mapped_column(String(1024))
    # Highest applied data_transformations.seq. Makes replay cheap and detects gaps.
    transform_seq: Mapped[int] = mapped_column(Integer, default=0, server_default="0")

    __table_args__ = (
        UniqueConstraint("dataset_id", "name", name="uq_worksheets_dataset_name"),
    )

    dataset: Mapped[Dataset] = relationship(back_populates="worksheets")
    columns: Mapped[list["Column"]] = relationship(
        back_populates="worksheet",
        cascade="all, delete-orphan",
        order_by="Column.ordinal",
    )
    transformations: Mapped[list["DataTransformation"]] = relationship(
        back_populates="worksheet",
        cascade="all, delete-orphan",
        order_by="DataTransformation.seq",
    )


class Column(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """Column metadata and ROLES.

    S2 3.3: "Column name . Unit . Data type / X/Y designation . Replicate designation .
    Group designation / Error column . Formula . Metadata".

    Key design point (docs/05-data-model.md 5.3): X/Y, replicate and group are
    INDEPENDENT, COMPOSABLE roles -- not one enum. A numeric column can be a Y, a
    replicate-bearing column, and in group "Sample A" simultaneously. Compressing them
    breaks the wizard's Step-1 dropdowns.
    """

    __tablename__ = "columns"
    __table_args__ = (
        UniqueConstraint("worksheet_id", "name", name="uq_columns_worksheet_name"),
        Index("ix_columns_worksheet_ordinal", "worksheet_id", "ordinal"),
    )

    worksheet_id: Mapped[str] = mapped_column(
        ForeignKey("worksheets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    unit: Mapped[str | None] = mapped_column(String(64))

    data_type: Mapped[ColumnDataType] = enum_col(ColumnDataType, "column_data_type")

    # --- roles (composable, per S2 3.3) ---
    role_x: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    role_y: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    is_replicate: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
    group_name: Mapped[str | None] = mapped_column(String(128), index=True)

    # An error column may point at another column in the same worksheet.
    error_column_id: Mapped[str | None] = mapped_column(
        ForeignKey("columns.id", ondelete="SET NULL")
    )

    formula: Mapped[str | None] = mapped_column(Text)
    metadata_: Mapped[dict | None] = mapped_column("metadata")

    # Refreshed after each transform so a column header never scans Parquet (ADR 0001).
    statistics: Mapped[dict | None] = mapped_column()

    worksheet: Mapped[Worksheet] = relationship(back_populates="columns", foreign_keys=[worksheet_id])
    error_column: Mapped["Column | None"] = relationship(foreign_keys=[error_column_id])


class DataTransformation(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """AN ORDERED, REPLAYABLE LOG -- IRREVERSIBLE.

    S2 3.13 provenance: "Processing: Normalization -> Log transformation".

    ``seq`` is dense and starts at 1 per worksheet. ``params`` holds every argument
    needed to re-execute the step. ``input_columns``/``output_columns`` name the
    columns read and produced, so Trace can walk the chain in both directions.

    Ordering is enforced by a unique constraint rather than trusted to application
    code: a duplicate or missing seq would silently corrupt every downstream
    provenance record.
    """

    __tablename__ = "data_transformations"
    __table_args__ = (
        UniqueConstraint("worksheet_id", "seq", name="uq_data_transformations_worksheet_seq"),
        Index("ix_data_transformations_worksheet_seq", "worksheet_id", "seq"),
    )

    worksheet_id: Mapped[str] = mapped_column(
        ForeignKey("worksheets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    seq: Mapped[int] = mapped_column(Integer, nullable=False)
    transform_type: Mapped[TransformType] = enum_col(TransformType, "transform_type")
    params: Mapped[dict] = mapped_column(default=dict, nullable=False)
    input_columns: Mapped[list | None] = mapped_column()
    output_columns: Mapped[list | None] = mapped_column()
    rows_before: Mapped[int | None] = mapped_column(Integer)
    rows_after: Mapped[int | None] = mapped_column(Integer)
    # Parquet artefact produced by this step, for replay without re-executing.
    output_store_key: Mapped[str | None] = mapped_column(String(1024))
    applied_by_id: Mapped[str | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    applied_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    worksheet: Mapped[Worksheet] = relationship(back_populates="transformations")
